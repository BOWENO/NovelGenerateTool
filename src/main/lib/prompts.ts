let promptsDir = ''

/** 首次初始化默认模板；升级保留作者已经修改的模板。 */
export function initPrompts(): void {
  promptsDir = join(app.getPath('userData'), 'prompts')
  mkdirSync(promptsDir, { recursive: true })
  for (const [id, content] of Object.entries(DEFAULT_PROMPTS)) {
    const p = join(promptsDir, id + '.md')
    if (!existsSync(p)) writeFileSync(p, content, 'utf-8')
  }
}

export function listPrompts(): string[] {
  return readdirSync(promptsDir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => f.replace(/\.md$/, ''))
}

export function getPrompt(id: string): string {
  const p = join(promptsDir, `${id}.md`)
  return existsSync(p) ? readFileSync(p, 'utf-8') : ''
}

export function savePrompt(id: string, content: string): void {
  if (!/^[a-zA-Z0-9-]+$/.test(id)) throw new Error('非法提示词 ID')
  writeFileSync(join(promptsDir, `${id}.md`), content, 'utf-8')
}

export function promptsDirPath(): string {
  return promptsDir
}

export function renderPrompt(tpl: string, vars: Record<string, string>): string {
  return tpl.replace(/\{\{(\w+)\}\}/g, (_, k: string) => vars[k] ?? '')
}
